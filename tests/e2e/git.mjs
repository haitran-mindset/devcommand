import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdtemp, rm, writeFile, readFile, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { _electron as electron } from 'playwright'
import { waitForIpc } from './wait.mjs'

const root = await mkdtemp(join(tmpdir(), 'devcommand-git-e2e-')), repo = join(root, 'repo Git 日本語')
execFileSync('git', ['init', '-b', 'main', repo], { stdio: 'ignore' })
const git = (args) => execFileSync('git', ['-C', repo, '-c', 'core.hooksPath=/dev/null', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
git(['config', 'user.name', 'Fixture']); git(['config', 'user.email', 'fixture@example.invalid'])
await writeFile(join(repo, 'tracked.txt'), 'base\n'); git(['add', '.']); git(['commit', '-m', 'Git manager initial fixture'])
git(['switch', '-c', 'unmerged']); await writeFile(join(repo, 'branch-only.txt'), 'unmerged\n'); git(['add', '.']); git(['commit', '-m', 'Unmerged fixture']); git(['switch', 'main'])
await writeFile(join(repo, 'tracked.txt'), 'worktree version\n')
const executablePath = process.env.DEVCOMMAND_EXECUTABLE, env = { ...process.env }
delete env.ELECTRON_RUN_AS_NODE
let app
try {
  app = await electron.launch({ env, ...(executablePath ? { executablePath } : {}), args: [...(executablePath ? [] : [resolve('.')]), `--user-data-dir=${join(root, 'profile')}`], timeout: 30000 })
  const page = await app.firstWindow(), errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.getByRole('heading', { name: 'Change Git Remote URL', exact: true }).waitFor()
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, repo)
  await page.getByRole('link', { name: 'Repositories', exact: true }).click()
  await page.getByRole('button', { name: 'Add repository', exact: true }).click()
  await page.getByRole('heading', { name: 'repo Git 日本語', exact: true }).waitFor()
  const workspaceId = await page.evaluate(async () => (await window.devcommand.workspace.list()).data.selectedId)
  assert.equal(await page.evaluate(async (workspaceId) => (await window.devcommand.git.snapshot({ workspaceId, section: 'overview', cwd: '/' })).ok, workspaceId), false)
  assert.equal(await page.evaluate(async (workspaceId) => (await window.devcommand.git.diff({ workspaceId, path: '../outside' })).ok, workspaceId), false)
  await page.getByRole('link', { name: 'Git Manager', exact: true }).click()
  await page.getByRole('button', { name: 'Stage tracked.txt', exact: true }).waitFor()
  const confirm = async (expected = 'succeeded') => {
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Confirm & Run', exact: true }).click()
    await dialog.getByRole('region', { name: 'Git operation result' }).getByRole('status').filter({ hasText: expected }).waitFor()
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Stage tracked.txt', exact: true }).click()
  assert.equal(git(['diff', '--cached', '--name-only']), '')
  await confirm()
  assert.equal(git(['diff', '--cached', '--name-only']), 'tracked.txt')
  await page.getByRole('button', { name: 'Staged diff tracked.txt', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.git-diff pre')?.textContent?.includes('+worktree version'))
  await page.getByRole('button', { name: 'Unstage tracked.txt', exact: true }).click()
  await confirm()
  assert.equal(git(['diff', '--cached', '--name-only']), '')
  assert.equal(await readFile(join(repo, 'tracked.txt'), 'utf8'), 'worktree version\n')
  await page.getByRole('button', { name: 'Worktree diff tracked.txt', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.git-diff pre')?.textContent?.includes('+worktree version'))
  await writeFile(join(repo, 'tracked.txt'), 'external refresh version\n')
  await page.getByRole('button', { name: 'Refresh Git', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.git-diff pre')?.textContent?.includes('+external refresh version'))
  await page.getByRole('tab', { name: 'Config', exact: true }).click()
  await page.getByRole('heading', { name: 'Git configuration', exact: true }).waitFor()
  assert.equal(await page.locator('.git-config-table tbody tr').count(), 5)
  assert.equal(await page.getByRole('region', { name: 'Commit identity', exact: true }).count(), 1)
  assert.equal(await page.getByRole('region', { name: 'Git behavior', exact: true }).count(), 1)
  assert.equal(await page.getByRole('button', { name: 'Edit local user.name', exact: true }).innerText(), '', 'Config edit controls are compact icon buttons')
  await mkdir('resources/screenshots', { recursive: true })
  for (const [width, height] of [[1280, 820], [900, 700], [1672, 941]]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setSize(...size), [width, height])
    await page.waitForFunction((width) => innerWidth === width, width)
    assert.equal(await page.locator('.git-config-panel').evaluate((panel) => panel.scrollWidth <= panel.clientWidth + 1), true, 'Config comparison fits the window')
    await page.screenshot({ path: `resources/screenshots/git-config-${executablePath ? 'packaged' : 'built'}-${width}.png` })
  }
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  await page.screenshot({ path: `resources/screenshots/git-config-${executablePath ? 'packaged' : 'built'}-light.png` })
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.getByRole('button', { name: 'Edit global user.name', exact: true }).click()
  assert.equal(await page.getByRole('combobox', { name: 'Scope', exact: true }).innerText(), 'Global')
  assert.equal(await page.locator('.git-config-form').evaluate((form) => {
    const scope = form.querySelector('[data-field=scope]').getBoundingClientRect()
    const key = form.querySelector('[data-field=key]').getBoundingClientRect()
    const value = form.querySelector('[data-field=value]').getBoundingClientRect()
    return Math.abs(scope.top - key.top) < 1 && value.top > scope.top && form.getBoundingClientRect().width <= 680
  }), true, 'Config form has a compact width, scope/key row and full-width value field')
  await page.getByText('Applies to all repositories for your user.', { exact: true }).waitFor()
  await page.locator('.git-config-form').screenshot({ path: `resources/screenshots/git-config-form-${executablePath ? 'packaged' : 'built'}.png` })

  await page.getByRole('button', { name: 'Cancel form', exact: true }).click()

  await page.getByRole('button', { name: 'Edit local user.name', exact: true }).click()
  await page.getByLabel('Config Value', { exact: true }).fill('Git Manager Fixture')
  await page.getByRole('button', { name: 'Review operation', exact: true }).click()
  await confirm()
  assert.equal(git(['config', 'user.name']), 'Git Manager Fixture')
  await page.getByRole('tab', { name: 'Remotes', exact: true }).click()
  await page.getByRole('button', { name: 'Add remote', exact: true }).click()
  await page.getByLabel('Remote URL', { exact: true }).fill('git@github.com:example/phase4.git')
  await page.getByRole('button', { name: 'Review operation', exact: true }).click()
  await confirm()
  assert.equal(git(['remote', 'get-url', 'origin']), 'git@github.com:example/phase4.git')
  await page.getByRole('button', { name: 'Rename remote origin', exact: true }).click()
  await page.getByLabel('New Remote Name', { exact: true }).fill('upstream')
  await page.getByRole('button', { name: 'Review operation', exact: true }).click()
  await confirm()
  assert.equal(git(['remote']), 'upstream')
  await page.getByRole('button', { name: 'Remove remote upstream', exact: true }).click()
  await page.getByRole('dialog').getByText('The remote configuration and its tracking references will be removed.', { exact: false }).waitFor()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  assert.equal(git(['remote']), 'upstream')
  await page.getByRole('button', { name: 'Remove remote upstream', exact: true }).click()
  await confirm()
  assert.equal(git(['remote']), '')
  await page.getByRole('tab', { name: 'Branches', exact: true }).click()
  await page.getByRole('button', { name: 'Delete branch unmerged', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Delete branch unmerged', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Create branch', exact: true }).click()
  await page.getByLabel('Branch Name', { exact: true }).fill('feature/ui')
  await page.getByRole('button', { name: 'Review operation', exact: true }).click()
  await confirm()
  await page.getByRole('button', { name: 'Rename branch feature/ui', exact: true }).click()
  await page.getByLabel('New Branch Name', { exact: true }).fill('feature/renamed')
  await page.getByRole('button', { name: 'Review operation', exact: true }).click()
  await confirm()
  await page.getByRole('button', { name: 'Switch feature/renamed', exact: true }).click()
  await confirm()
  assert.equal(git(['branch', '--show-current']), 'feature/renamed')
  await page.getByRole('button', { name: 'Switch main', exact: true }).click()
  await confirm()
  await page.getByRole('button', { name: 'Delete branch feature/renamed', exact: true }).click()
  await confirm()
  assert.equal(git(['branch', '--list', 'feature/renamed']), '')
  await page.getByRole('tab', { name: 'Commits', exact: true }).click()
  const oid = git(['rev-parse', 'HEAD'])
  await page.getByRole('button', { name: `Inspect commit ${oid.slice(0, 7)}`, exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.git-diff pre')?.textContent?.includes('Git manager initial fixture'))
  await page.getByRole('tab', { name: 'Stash', exact: true }).click()
  await page.getByRole('button', { name: 'Save tracked changes', exact: true }).click()
  await confirm()
  assert.equal(git(['diff']), '')
  await page.getByRole('button', { name: 'Apply stash@{0}', exact: true }).click()
  await confirm()
  assert.equal(await readFile(join(repo, 'tracked.txt'), 'utf8'), 'external refresh version\n')
  assert.notEqual(git(['stash', 'list']), '')
  git(['restore', '--worktree', '--', 'tracked.txt'])
  await page.getByRole('button', { name: 'Refresh Git', exact: true }).click()
  await page.getByRole('button', { name: 'Pop stash@{0}', exact: true }).click()
  await page.getByRole('dialog').getByText('Applies the stash and drops it only on success.', { exact: false }).waitFor()
  await confirm()
  assert.equal(git(['stash', 'list']), '')
  await page.getByRole('button', { name: 'Save tracked changes', exact: true }).click()
  await confirm()
  await page.getByRole('button', { name: 'Drop stash@{0}', exact: true }).click()
  await page.getByRole('dialog').getByText('Permanently removes this saved stash', { exact: false }).waitFor()
  await confirm()
  assert.equal(git(['stash', 'list']), '')
  // Make a real conflict from a saved stash; the manager must show it and retain the stash.
  await writeFile(join(repo, 'tracked.txt'), 'stash side\n'); git(['stash', 'push'])
  await writeFile(join(repo, 'tracked.txt'), 'branch side\n'); git(['add', '.']); git(['commit', '-m', 'Conflict fixture'])
  let conflicted = false
  try { git(['stash', 'apply']) } catch (failure) { conflicted = String(failure.stdout ?? '').includes('CONFLICT') }
  assert.equal(conflicted, true)
  assert.notEqual(git(['stash', 'list']), '')
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await waitForIpc(page, async (workspaceId) => (await window.devcommand.git.snapshot({ workspaceId, section: 'overview' })).data.status.conflicts, workspaceId)
  await page.getByRole('alert').filter({ hasText: 'Merge conflicts are present' }).waitFor()
  await mkdir('resources/screenshots', { recursive: true })
  await page.screenshot({ path: `resources/screenshots/phase4-${executablePath ? 'packaged' : 'built'}.png` })
  assert.deepEqual(errors, [])
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 700))
  await page.waitForFunction(() => innerWidth === 900)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  console.log(`PASS: ${executablePath ? 'packaged' : 'built'} Git Manager staging/diffs/config/remotes/branches/commits/stash, explicit confirmations, refresh and conflict UI.`)
} finally {
  await app?.close().catch(() => {})
  await rm(root, { recursive: true, force: true })
}
